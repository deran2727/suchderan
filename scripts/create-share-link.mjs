import {
  createPrivateKey,
  createPublicKey,
  generateKeyPairSync,
  randomBytes,
  sign,
  verify,
} from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const DEFAULT_ORIGIN = 'https://deran2727.github.io/suchderan/';
const MAX_DAYS = 3;
const keyDirectory = path.resolve('.share-access');
const privateKeyPath = path.join(keyDirectory, 'private-key.pem');
const publicKeyModulePath = path.resolve('src/share-public-key.js');

function readArgument(name, fallback) {
  const inline = process.argv.find(value => value.startsWith(`${name}=`));
  if (inline) return inline.slice(name.length + 1);
  const index = process.argv.indexOf(name);
  return index >= 0 ? process.argv[index + 1] : fallback;
}

async function loadOrCreatePrivateKey() {
  await mkdir(keyDirectory, { recursive: true });
  try {
    return createPrivateKey(await readFile(privateKeyPath, 'utf8'));
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
    const { privateKey } = generateKeyPairSync('ec', { namedCurve: 'prime256v1' });
    const pem = privateKey.export({ type: 'pkcs8', format: 'pem' });
    await writeFile(privateKeyPath, pem, { encoding: 'utf8', mode: 0o600, flag: 'wx' });
    return privateKey;
  }
}

const days = Number(readArgument('--days', String(MAX_DAYS)));
if (!Number.isFinite(days) || days <= 0 || days > MAX_DAYS) {
  throw new Error(`--days must be greater than 0 and no more than ${MAX_DAYS}.`);
}

const origin = new URL(readArgument('--origin', DEFAULT_ORIGIN));
const privateKey = await loadOrCreatePrivateKey();
const publicKey = createPublicKey(privateKey);
const publicJwk = publicKey.export({ format: 'jwk' });
const now = Math.floor(Date.now() / 1000);
const expiresAt = now + Math.round(days * 24 * 60 * 60);
const payload = {
  v: 1,
  purpose: 'portfolio-preview',
  iat: now,
  exp: expiresAt,
  jti: randomBytes(12).toString('base64url'),
};
const encodedPayload = Buffer.from(JSON.stringify(payload)).toString('base64url');
const signature = sign('sha256', Buffer.from(encodedPayload), {
  key: privateKey,
  dsaEncoding: 'ieee-p1363',
});

if (!verify('sha256', Buffer.from(encodedPayload), {
  key: publicKey,
  dsaEncoding: 'ieee-p1363',
}, signature)) {
  throw new Error('Generated share token failed its signature self-check.');
}

const publicKeyModule = `// Generated by scripts/create-share-link.mjs. Safe to deploy.\nexport const SHARE_PUBLIC_KEY = ${JSON.stringify(publicJwk, null, 2)};\n`;
await writeFile(publicKeyModulePath, publicKeyModule, 'utf8');

origin.searchParams.set('share', `${encodedPayload}.${signature.toString('base64url')}`);
origin.hash = 'home';

console.log(`Temporary link (${days} days):`);
console.log(origin.toString());
console.log(`Expires: ${new Date(expiresAt * 1000).toLocaleString('zh-CN', { timeZone: 'Asia/Shanghai', hour12: false })} Asia/Shanghai`);
